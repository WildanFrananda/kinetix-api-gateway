#!/usr/bin/env bash
# Route conformance for the Kinetix gateway. (S2 / P1-GW-03)
#
# Asserts two things that no amount of reading gateway.pkl can establish:
#
#   1. EVERY UPSTREAM RESOLVES. Each service url in the GENERATED kong.yml names a host that
#      actually exists on the `kinetix` network. The audit's finding was that not one of them
#      did; the file looked correct and routed to nothing.
#
#   2. NO PUBLIC PATH IS A 404. Every declared route is requested through the gateway and must
#      not come back 404 — the signature of a strip_path that rewrote the resource name away,
#      or of a route pointing at an endpoint the upstream never had.
#
# Driven from the kong.yml the image actually carries, not from a list maintained by hand:
# a route added to gateway.pkl is tested by the next run without anyone remembering to add it.
#
# Usage:  test/route_conformance.sh [base-url]        (default https://localhost:8443)
#
# The gateway serves TLS only. Its certificate is signed by a per-environment CA, so the CA has
# to be on hand — set CA_FILE, or let this script take it from the infrastructure repo's
# rendered .env. Verification is left on: without it this suite could not tell a real
# certificate from a self-signed default.

set -uo pipefail

BASE="${1:-https://localhost:8443}"

CA_FILE="${CA_FILE:-}"
if [ -z "$CA_FILE" ]; then
  ENV_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/kinetix-infrastructure/.env"
  if [ -f "$ENV_FILE" ]; then
    CA_FILE="$(mktemp)"
    awk -F= '/^KINETIX_GATEWAY_TLS_CA_B64=/{print substr($0, index($0,"=")+1)}' "$ENV_FILE" \
      | base64 -d > "$CA_FILE" 2>/dev/null || true
  fi
fi
if [ ! -s "${CA_FILE:-/nonexistent}" ] || ! grep -q "BEGIN CERTIFICATE" "$CA_FILE" 2>/dev/null; then
  echo "no gateway CA available. Set CA_FILE, or run bin/kinetix-secrets render dev in kinetix-infrastructure." >&2
  exit 1
fi
CURL=(curl --cacert "$CA_FILE")
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE="$HERE/../kinetix-infrastructure/compose.yaml"

pass=0; fail=0
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; pass=$((pass+1)); }
bad()  { printf '  \033[31m✗\033[0m %s\n' "$*"; fail=$((fail+1)); }

gw_container() { docker compose -f "$COMPOSE" ps -q kinetix-api-gateway; }

GW="$(gw_container)"
[ -n "$GW" ] || { echo "gateway container is not running: docker compose -f $COMPOSE up -d"; exit 1; }

KONG_YML="$(docker exec "$GW" cat /usr/local/kong/declarative/kong.yml)"

# Extract (url, path...) pairs from the declarative config without a YAML library — the file
# is generated by pkl with a fixed shape, so the indentation is stable.
parse() {
  printf '%s\n' "$KONG_YML" | awk '
    /^- name: /            { svc=substr($0,9) }
    /^  url: /             { url=substr($0,8) }
    /^  - name: /          { hosted=0 }
    /^    hosts:/          { hosted=1 }
    /^    - \// && !hosted { print svc "\t" url "\t" substr($0,7) }
  '
}

upstreams() {
  printf '%s\n' "$KONG_YML" | awk '
    /^- name: /            { svc=substr($0,9) }
    /^  url: /             { print svc "\t" substr($0,8) }
  '
}

echo "── 1. Every upstream host resolves from inside the gateway"
seen=""
while IFS=$'\t' read -r svc url; do
  host="$(printf '%s' "$url" | sed -E 's#https?://([^:/]+).*#\1#')"
  case " $seen " in *" $host "*) continue ;; esac
  seen="$seen $host"
  [ "$host" = "127.0.0.1" ] && continue
  if docker exec "$GW" getent hosts "$host" >/dev/null 2>&1; then
    ok "$host resolves"
  else
    bad "$host does NOT resolve — no container answers to this name"
  fi
done < <(upstreams)

echo
echo "── 2. Every declared public path reaches its upstream"
#
# A 404 is not automatically a failure, and treating it as one made this suite cry wolf on its
# first full run. Two very different things return 404 here:
#
#   Kong itself, when no route matches      -> {"message":"no Route matched with those values"}
#   the upstream, when the path has no handler -> the framework's own body, e.g.
#                                              {"message":"Cannot GET /api/auth", ...}
#
# The second is the correct answer to a request for a bare resource prefix — /api/v1/auth is a
# route namespace, not an endpoint; the endpoints under it are /login and /register. Getting
# the application's own 404 proves the hop worked, which is exactly what this suite exists to
# check. Only Kong's own 404 means the route is not wired.
while IFS=$'\t' read -r svc url path; do
  body="$("${CURL[@]}" -s --max-time 10 "$BASE$path")"
  code="$("${CURL[@]}" -s -o /dev/null -w '%{http_code}' --max-time 10 "$BASE$path")"
  case "$code" in
    000) bad "$path -> no response  ($svc)  gateway unreachable or timed out" ;;
    404)
      if printf '%s' "$body" | grep -q 'no Route matched'; then
        bad "$path -> 404 from Kong  ($svc)  no route matches this path"
      else
        ok "$path -> 404 from the upstream  ($svc)  reached the app; no handler at this prefix"
      fi ;;
    5*)  bad "$path -> $code  ($svc)  upstream unreachable or erroring" ;;
    *)   ok  "$path -> $code  ($svc)" ;;
  esac
done < <(parse)

echo
echo "── 3. The 404 detector is not fooled"
# Negative control. Check 2 passes an upstream 404, so it is only meaningful if a genuinely
# unrouted path still fails. Without this the suite could pass by treating every 404 as fine.
ctl="$("${CURL[@]}" -s --max-time 10 "$BASE/definitely-not-a-declared-route")"
if printf '%s' "$ctl" | grep -q 'no Route matched'; then
  ok "an undeclared path is refused by Kong, so check 2 can tell the two 404s apart"
else
  bad "an undeclared path did NOT produce Kong's 404 — check 2's distinction is meaningless"
fi

echo
echo "── 4. The gateway is the only thing on the host"
published="$(docker compose -f "$COMPOSE" config --format json \
  | python3 -c 'import json,sys;d=json.load(sys.stdin);print(sum(len(v.get("ports") or []) for v in d["services"].values()))')"
if [ "$published" = "1" ]; then
  ok "exactly one published port mapping in compose.yaml"
else
  bad "$published published port mappings — expected 1 (the gateway)"
fi

echo
echo "── 5. The staff gate gives every admin-only route the same answer, and no public route"
GATE_MESSAGE="This route is not available from your network"
gated=0; reached=0
gate_answer() {
  local method="$1" path="$2" body code
  body="$("${CURL[@]}" -s --max-time 10 -X "$method" -w '\n%{http_code}' "$BASE$path")"
  code="${body##*$'\n'}"
  body="${body%$'\n'*}"
  if [ "$code" = 403 ] && printf '%s' "$body" | grep -qF "$GATE_MESSAGE"; then
    echo gated
  elif [ "$code" = 404 ] && printf '%s' "$body" | grep -q 'no Route matched'; then
    echo unrouted
  else
    echo "reached:$code"
  fi
}
while read -r method path; do
  answer="$(gate_answer "$method" "$path")"
  case "$answer" in
    gated)    gated=$((gated+1)) ;;
    reached*) reached=$((reached+1)) ;;
    *)        bad "$method $path -> $answer  (an admin-only path no route serves)" ;;
  esac
done <<'ADMIN'
POST /api/v1/categories
PUT /api/v1/categories/1
DELETE /api/v1/categories/1
POST /api/v1/warehouse/bins
POST /api/v1/warehouse/stock_receipts
POST /api/v1/warehouse/stock_adjustments
GET /api/v1/orders/sagas/needs-attention
GET /api/v1/orders/returns/needs-attention
POST /api/v1/orders/returns/RET-0/reject
POST /api/v1/orders/ORD-0/complete
ADMIN
if [ "$gated" -gt 0 ] && [ "$reached" -gt 0 ]; then
  bad "$gated admin-only routes refused this address and $reached let it through: a route lost its gate"
elif [ "$gated" -gt 0 ]; then
  ok "this address is outside the staff range: all $gated admin-only routes answered the gate's 403"
else
  ok "this address is inside the staff range: all $reached admin-only routes reached their service"
fi
while read -r method path; do
  answer="$(gate_answer "$method" "$path")"
  case "$answer" in
    gated) bad "$method $path -> the staff gate refused a public route" ;;
    *)     ok  "$method $path -> not gated ($answer)" ;;
  esac
done <<'PUBLIC'
GET /api/v1/categories
GET /api/v1/products/
GET /api/v1/warehouse/fulfillment_tasks
POST /api/v1/orders/checkout
GET /api/v1/orders/my-orders
PUBLIC

header_of() {
  tr -d '\r' < "$1" | grep -i "^$2:" | head -n 1 | cut -d' ' -f2-
}

is_archive() {
  [ "$(head -c 7 "$1")" = PMTiles ]
}

tile_answer() {
  local what="$1" code="$2" headers="$3" body="$4" limit
  limit="$(header_of "$headers" x-ratelimit-limit-minute)"
  if [ "$code" = 403 ] && grep -qF "$GATE_MESSAGE" "$body"; then
    ok "$what -> 403 from the staff gate (this address is outside the staff range)"
    return
  fi

  if [ "$limit" != 1200 ]; then
    bad "$what -> $code with limit '${limit:-none}': not the /tiles/ route (wanted its map-tile limit, 1200)"
    return
  fi

  case "$code" in
    206)
      if is_archive "$body" && [ -n "$(header_of "$headers" content-range)" ] && [ -n "$(header_of "$headers" etag)" ]; then
        ok "$what -> 206 through the /tiles/ route (limit 1200): a PMTiles archive's first 16 KiB, with Content-Range and ETag"
      elif is_archive "$body"; then
        bad "$what -> 206 without Content-Range '$(header_of "$headers" content-range)' or ETag '$(header_of "$headers" etag)'"
      else
        bad "$what -> 206 of $(header_of "$headers" content-type), not a PMTiles archive: the backoffice serves no /tiles/ yet (F5 not deployed)"
      fi ;;
    404) bad "$what -> 404 from the backoffice: no basemap in its volume (kinetix-infrastructure: bin/kinetix basemap fetch dev)" ;;
    502|503|504) bad "$what -> $code: kinetix-backoffice is not reachable (is it running?)" ;;
    *) bad "$what -> $code through the /tiles/ route (wanted the app's 206)" ;;
  esac
}

app_limit_answer() {
  local what="$1" code="$2" headers="$3" limit
  limit="$(header_of "$headers" x-ratelimit-limit-minute)"
  if [ "$code" = 403 ]; then
    return
  fi

  if [ "$limit" = 100 ]; then
    ok "$what -> the app route's own limit, 100 a minute, not the map tiles'"
  else
    bad "$what -> $code with limit '${limit:-none}' (wanted the app route's 100)"
  fi
}

echo
echo "── 6. The browser-app hosts: /bff/ to the edge, /tiles/ and the backoffice host's other paths to its app, the seller host's to a 404"
base_authority="${BASE#https://}"
base_authority="${base_authority%%/*}"
BACKOFFICE_CA_FILE="${BACKOFFICE_CA_FILE:-$HERE/../kinetix-infrastructure/pki/backoffice/ca.crt}"
for variable in KINETIX_BACKOFFICE_HOST KINETIX_SELLER_HOST; do
  app="$(docker exec "$GW" printenv "$variable" 2>/dev/null || true)"
  if [ -z "$app" ]; then
    bad "$variable is not set on the gateway"
    continue
  fi
  app_name="${app%%:*}"
  app_port="${app##*:}"
  [ "$app_port" = "$app" ] && app_port=443
  route=(--connect-to "$app_name:$app_port:$base_authority")
  app_curl=("${CURL[@]}")
  certificate="the gateway's certificate"
  if [ "$variable" = KINETIX_BACKOFFICE_HOST ]; then
    if [ ! -s "$BACKOFFICE_CA_FILE" ]; then
      bad "no backoffice CA at $BACKOFFICE_CA_FILE: run bin/kinetix backoffice tls dev in kinetix-infrastructure, or set BACKOFFICE_CA_FILE"
      continue
    fi

    app_curl=(curl --cacert "$BACKOFFICE_CA_FILE")
    certificate="the backoffice host's certificate"
    code="$("${app_curl[@]}" -s -o /dev/null -w '%{http_code}' --max-time 10 "${route[@]}" "https://$app_name:$app_port/")"
    if [ "$code" != 000 ]; then
      ok "$app presents the backoffice host's own certificate, and it verifies against the backoffice CA"
    else
      bad "$app's certificate does not verify against $BACKOFFICE_CA_FILE (does the gateway run with KINETIX_BACKOFFICE_TLS_CERT_B64 for $app_name?)"
    fi

    code="$("${CURL[@]}" -s -o /dev/null -w '%{http_code}' --max-time 10 "${route[@]}" "https://$app_name:$app_port/")"
    if [ "$code" = 000 ]; then
      ok "$app does not present the public listener's default certificate"
    else
      bad "$app verified against the gateway CA ($code): the default certificate answers its SNI, not the backoffice host's"
    fi
  fi

  body="$("${app_curl[@]}" -s --max-time 10 "${route[@]}" -w '\n%{http_code}' "https://$app_name:$app_port/api/v1/products")"
  code="${body##*$'\n'}"
  body="${body%$'\n'*}"
  if [ "$variable" = KINETIX_BACKOFFICE_HOST ]; then
    if [ "$code" = 403 ] && printf '%s' "$body" | grep -qF "$GATE_MESSAGE"; then
      ok "$app/api/v1/products -> 403 from the staff gate (this address is outside the staff range)"
    elif [ "$code" = 200 ] && printf '%s' "$body" | grep -qF '<title>Kinetix Backoffice</title>'; then
      ok "$app/api/v1/products -> the backoffice app's page: no API route answers on this host"
    elif [ "$code" = 502 ] || [ "$code" = 503 ] || [ "$code" = 504 ]; then
      bad "$app/api/v1/products -> $code: kinetix-backoffice is not reachable (is it running?)"
    else
      bad "$app/api/v1/products -> $code $body (wanted the backoffice app; is $app_name on $certificate?)"
    fi
  elif [ "$code" = 404 ] && printf '%s' "$body" | grep -qF '"message":"Not found"'; then
    ok "$app/api/v1/products -> 404: no API route answers on this host"
  else
    bad "$app/api/v1/products -> $code $body (wanted the browser-app host's 404; is $app_name on $certificate?)"
  fi
  body="$("${app_curl[@]}" -s --max-time 10 "${route[@]}" -w '\n%{http_code}' "https://$app_name:$app_port/bff/session")"
  code="${body##*$'\n'}"
  body="${body%$'\n'*}"
  case "$code" in
    000) bad "$app/bff/session -> no response (TLS name or connection)" ;;
    404)
      if printf '%s' "$body" | grep -qE 'no Route matched|"message":"Not found"'; then
        bad "$app/bff/session -> 404 from Kong: /bff/ is not routed on this host"
      else
        ok "$app/bff/session -> 404 from the edge"
      fi ;;
    403)
      if printf '%s' "$body" | grep -qF "$GATE_MESSAGE"; then
        ok "$app/bff/session -> 403 from the staff gate (this address is outside the staff range)"
      else
        ok "$app/bff/session -> 403 from the edge"
      fi ;;
    502|503|504) bad "$app/bff/session -> $code: the edge is not reachable" ;;
    *) ok "$app/bff/session -> $code from the edge" ;;
  esac

  if [ "$variable" = KINETIX_BACKOFFICE_HOST ]; then
    tile_headers="$(mktemp)"
    tile_body="$(mktemp)"
    code="$("${app_curl[@]}" -s --max-time 30 "${route[@]}" -H "Range: bytes=0-16383" -D "$tile_headers" -o "$tile_body" -w '%{http_code}' "https://$app_name:$app_port/tiles/basemap.pmtiles")"
    tile_answer "$app/tiles/basemap.pmtiles (Range: bytes=0-16383)" "$code" "$tile_headers" "$tile_body"
    if [ "$code" = 206 ] && is_archive "$tile_body"; then
      etag="$(header_of "$tile_headers" etag)"
      code="$("${app_curl[@]}" -s --max-time 30 "${route[@]}" -H "Range: bytes=0-16383" -H "If-None-Match: $etag" -o /dev/null -w '%{http_code}' "https://$app_name:$app_port/tiles/basemap.pmtiles")"
      if [ "$code" = 304 ]; then
        ok "$app/tiles/basemap.pmtiles with If-None-Match: its ETag -> 304 from the backoffice"
      else
        bad "$app/tiles/basemap.pmtiles with If-None-Match: its ETag -> $code (wanted 304)"
      fi
    fi

    code="$("${app_curl[@]}" -s --max-time 10 "${route[@]}" -D "$tile_headers" -o /dev/null -w '%{http_code}' "https://$app_name:$app_port/")"
    app_limit_answer "$app/" "$code" "$tile_headers"
    rm -f "$tile_headers" "$tile_body"
  fi
done

echo
echo "── 7. The internal listener: twins in plaintext, never over TLS, never published"
if [ -z "$(docker port "$GW" 8000 2>/dev/null)" ]; then
  ok "port 8000 is not published"
else
  bad "port 8000 is published: $(docker port "$GW" 8000)"
fi
network="$(docker inspect -f '{{range $name, $_ := .NetworkSettings.Networks}}{{$name}} {{end}}' "$GW" | awk '{print $1}')"
internal() {
  docker run --rm --network "$network" alpine:3.22.2@sha256:4b7ce07002c69e8f3d704a9c5d6fd3053be500b7f1c69fc0d80990c2ad8dd412 \
    wget -q -S -O /dev/null "${@:2}" "http://kinetix-api-gateway:8000$1" 2>&1 | awk '/^  HTTP\// { code=$2 } END { print code }'
}
upgrade_headers=(
  --header "Connection: Upgrade"
  --header "Upgrade: websocket"
  --header "Sec-WebSocket-Version: 13"
  --header "Sec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ=="
)
code="$(internal /api/v1/products/)"
case "$code" in
  ""|426|404|5*) bad "plaintext /api/v1/products/ -> '${code}': the twin did not reach catalog" ;;
  *) ok "plaintext /api/v1/products/ -> $code from catalog through its twin" ;;
esac
code="$(internal /health)"
if [ "$code" = 426 ]; then
  ok "plaintext /health -> 426: no twin for the static routes"
else
  bad "plaintext /health -> '$code' (wanted 426)"
fi
code="$("${CURL[@]}" -s -o /dev/null -w '%{http_code}' --max-time 10 -H "Host: kinetix-api-gateway" "$BASE/api/v1/products/")"
if [ "$code" = 421 ]; then
  ok "TLS naming the internal host -> 421: no twin answers the public listener"
else
  bad "TLS naming the internal host -> $code (wanted 421)"
fi
code="$(internal /ws/v1/matching/merchant/websocket "${upgrade_headers[@]}")"
case "$code" in
  ""|426|404|5*) bad "plaintext upgrade to /ws/v1/matching/merchant/websocket -> '${code}': the twin did not reach matching" ;;
  *) ok "plaintext upgrade to /ws/v1/matching/merchant/websocket -> $code from matching through its twin" ;;
esac
code="$(internal /ws/v1/matching/driver/websocket "${upgrade_headers[@]}")"
if [ "$code" = 426 ]; then
  ok "plaintext upgrade to /ws/v1/matching/driver/websocket -> 426: the driver socket has no twin"
else
  bad "plaintext upgrade to /ws/v1/matching/driver/websocket -> '$code' (wanted 426)"
fi

echo
echo "── 8. Kong reads a token from the Authorization header only"
for where in "query" "cookie"; do
  if [ "$where" = query ]; then
    body="$("${CURL[@]}" -s --max-time 10 "$BASE/api/v1/auth/me?jwt=not-a-token")"
  else
    body="$("${CURL[@]}" -s --max-time 10 -H "Cookie: jwt=not-a-token" "$BASE/api/v1/auth/me")"
  fi
  if printf '%s' "$body" | grep -qF '"message":"Unauthorized"'; then
    ok "GET /api/v1/auth/me with a token in the $where -> 401 Unauthorized: not read (a token read there would be refused as a bad token)"
  else
    bad "GET /api/v1/auth/me with a token in the $where -> $body (wanted the jwt plugin's 401 for a missing token)"
  fi
done

echo
echo "── 9. The onion listeners: the backoffice over TLS on 8444, 8081 redirecting to it, neither published"
onion="$(docker exec "$GW" printenv KINETIX_BACKOFFICE_ONION_HOST 2>/dev/null || true)"
ONION_CA_FILE="${ONION_CA_FILE:-$HERE/../kinetix-infrastructure/pki/onion/ca.crt}"
if [ -z "$onion" ]; then
  bad "KINETIX_BACKOFFICE_ONION_HOST is not set on the gateway"
else
  for port in 8081 8444; do
    if [ -z "$(docker port "$GW" "$port" 2>/dev/null)" ]; then
      ok "port $port is not published"
    else
      bad "port $port is published: $(docker port "$GW" "$port")"
    fi
  done

  on_listener() {
    docker run --rm --network "$network" alpine:3.22.2@sha256:4b7ce07002c69e8f3d704a9c5d6fd3053be500b7f1c69fc0d80990c2ad8dd412 \
      wget -S -O - --header "Host: $onion" "http://kinetix-api-gateway:$1$2" 2>&1
  }
  over_tls() {
    printf 'GET %s HTTP/1.1\r\nHost: %s\r\nConnection: close\r\n\r\n' "$1" "$onion" \
      | docker exec -i "$GW" sh -c 'openssl s_client -quiet -connect 127.0.0.1:8444 -servername "$KINETIX_BACKOFFICE_ONION_HOST" 2>/dev/null'
  }
  status_of() {
    awk '/^  HTTP\// { code=$2 } END { print code }'
  }
  first_status_of() {
    awk '/^ *HTTP\// { print $2; exit }'
  }

  if [ ! -s "$ONION_CA_FILE" ]; then
    bad "no onion CA at $ONION_CA_FILE: run bin/kinetix onion tls dev in kinetix-infrastructure, or set ONION_CA_FILE"
  else
    verified="$(docker exec -i "$GW" sh -c 'served="$(mktemp)"; openssl s_client -connect 127.0.0.1:8444 -servername "$KINETIX_BACKOFFICE_ONION_HOST" </dev/null 2>/dev/null | openssl x509 > "$served" 2>/dev/null; openssl verify -CAfile /dev/stdin -verify_hostname "$KINETIX_BACKOFFICE_ONION_HOST" "$served" >/dev/null 2>&1 && echo verified; rm -f "$served"' < "$ONION_CA_FILE")"
    if [ "$verified" = verified ]; then
      ok "8444 presents the onion address's certificate, and it verifies against the onion CA"
    else
      bad "8444's certificate for the onion address does not verify against $ONION_CA_FILE"
    fi
  fi

  answer="$(over_tls /api/v1/products)"
  if [ "$(printf '%s\n' "$answer" | tr -d '\r' | first_status_of)" = 200 ] && printf '%s' "$answer" | grep -qF '<title>Kinetix Backoffice</title>'; then
    ok "the onion address /api/v1/products on 8444 -> the backoffice app's page: no API route answers there"
  else
    bad "the onion address /api/v1/products on 8444 -> $(printf '%s\n' "$answer" | tr -d '\r' | first_status_of) (wanted the backoffice app; is it running?)"
  fi
  answer="$(over_tls /bff/session)"
  code="$(printf '%s\n' "$answer" | tr -d '\r' | first_status_of)"
  if [ -z "$code" ] || [ "$code" = 502 ] || [ "$code" = 503 ] || [ "$code" = 504 ]; then
    bad "the onion address /bff/session on 8444 -> '$code': the edge is not reachable"
  elif printf '%s' "$answer" | grep -qE 'no Route matched|Misdirected Request'; then
    bad "the onion address /bff/session on 8444 -> $code from Kong, not the edge"
  else
    ok "the onion address /bff/session on 8444 -> $code from the edge"
  fi

  answer="$(on_listener 8081 /bff/session)"
  if [ "$(printf '%s\n' "$answer" | first_status_of)" = 308 ] && printf '%s' "$answer" | grep -qF "Location: https://$onion/bff/session"; then
    ok "the onion address /bff/session on 8081 -> 308 to https://<the onion address>/bff/session, no port"
  else
    bad "the onion address /bff/session on 8081 -> $(printf '%s\n' "$answer" | first_status_of) (wanted 308 to the same path over HTTPS)"
  fi

  over_tls_to() {
    local out="$1" path="$2" line
    shift 2
    {
      printf 'GET %s HTTP/1.1\r\nHost: %s\r\n' "$path" "$onion"
      for line in "$@"; do
        printf '%s\r\n' "$line"
      done
      printf 'Connection: close\r\n\r\n'
    } | docker exec -i "$GW" sh -c 'openssl s_client -quiet -connect 127.0.0.1:8444 -servername "$KINETIX_BACKOFFICE_ONION_HOST" 2>/dev/null' > "$out"
  }
  split_response() {
    python3 - "$1" "$2" "$3" <<'PY'
import sys

data = open(sys.argv[1], "rb").read()
head, _, body = data.partition(b"\r\n\r\n")
open(sys.argv[2], "wb").write(head + b"\r\n")
open(sys.argv[3], "wb").write(body)
PY
  }
  onion_raw="$(mktemp)"
  onion_headers="$(mktemp)"
  onion_body="$(mktemp)"

  over_tls_to "$onion_raw" /tiles/basemap.pmtiles "Range: bytes=0-16383"
  split_response "$onion_raw" "$onion_headers" "$onion_body"
  code="$(head -n 1 "$onion_headers" | awk '{ print $2 }')"
  tile_answer "the onion address /tiles/basemap.pmtiles on 8444 (Range: bytes=0-16383)" "$code" "$onion_headers" "$onion_body"
  if [ "$code" = 206 ] && is_archive "$onion_body"; then
    etag="$(header_of "$onion_headers" etag)"
    over_tls_to "$onion_raw" /tiles/basemap.pmtiles "Range: bytes=0-16383" "If-None-Match: $etag"
    split_response "$onion_raw" "$onion_headers" "$onion_body"
    code="$(head -n 1 "$onion_headers" | awk '{ print $2 }')"
    if [ "$code" = 304 ]; then
      ok "the onion address /tiles/basemap.pmtiles on 8444 with If-None-Match: its ETag -> 304 from the backoffice"
    else
      bad "the onion address /tiles/basemap.pmtiles on 8444 with If-None-Match: its ETag -> '$code' (wanted 304)"
    fi
  fi

  over_tls_to "$onion_raw" /
  split_response "$onion_raw" "$onion_headers" "$onion_body"
  code="$(head -n 1 "$onion_headers" | awk '{ print $2 }')"
  app_limit_answer "the onion address / on 8444" "$code" "$onion_headers"
  rm -f "$onion_raw" "$onion_headers" "$onion_body"

  answer="$(on_listener 8081 /tiles/basemap.pmtiles)"
  if [ "$(printf '%s\n' "$answer" | first_status_of)" = 308 ] && printf '%s' "$answer" | grep -qF "Location: https://$onion/tiles/basemap.pmtiles"; then
    ok "the onion address /tiles/basemap.pmtiles on 8081 -> 308 to https://<the onion address>/tiles/basemap.pmtiles, no port"
  else
    bad "the onion address /tiles/basemap.pmtiles on 8081 -> $(printf '%s\n' "$answer" | first_status_of) (wanted 308 to the same path over HTTPS)"
  fi
  code="$(on_listener 8000 /bff/session | status_of)"
  if [ "$code" = 421 ]; then
    ok "the onion address on the internal listener 8000 -> 421 from the onion routes' guard"
  else
    bad "the onion address on the internal listener 8000 -> '$code' (wanted 421)"
  fi
  code="$("${CURL[@]}" -s -o /dev/null -w '%{http_code}' --max-time 10 -H "Host: $onion" "$BASE/bff/session")"
  if [ "$code" = 421 ]; then
    ok "TLS on the public listener naming the onion address -> 421: the onion routes never answer it"
  else
    bad "TLS on the public listener naming the onion address -> $code (wanted 421)"
  fi
fi

